#!/usr/bin/env python3
"""Render a standalone nginx TLS proxy from a SPARK-validated remote profile."""
import argparse
import json
from pathlib import Path
import subprocess
from urllib.parse import urlsplit


def quote(value):
    # nginx expands variables even inside quoted strings. Reject them in paths.
    value = str(value)
    if any(c in value for c in '\x00\r\n$'):
        raise ValueError('Unsupported character in nginx path')
    return '"' + value.replace('\\', '\\\\').replace('"', '\\"') + '"'


def render(summary, certificate, key, module, runtime, tcp_only=False):
    if not summary.get('remote') or summary['auth_mode'] != 'required' or summary['server']['host'] != '127.0.0.1':
        raise ValueError('A validated remote profile is required')
    origin = urlsplit(summary['browser_origin'])
    https = origin.port or 443
    tcp = summary['public_notifications']['port']
    backend = summary['server']
    # Dedicated config: no distro defaults, port 80, static files or extra sites.
    common = f'''# Generated by SPARK scripts/configure-remote.py. Run as a dedicated foreground process.
load_module {quote(module)};
daemon off;
worker_processes 1;
pid {quote(runtime / 'nginx.pid')};
# Suppress request/URL/header logging, including accidentally supplied credentials.
error_log /dev/null;
events {{ worker_connections 1024; }}
'''
    http_config = f'''http {{
    access_log off;
    server_tokens off;
    client_body_temp_path {quote(runtime / 'body')};
    proxy_temp_path {quote(runtime / 'proxy')};
    fastcgi_temp_path {quote(runtime / 'fastcgi')};
    uwsgi_temp_path {quote(runtime / 'uwsgi')};
    scgi_temp_path {quote(runtime / 'scgi')};
    ssl_protocols TLSv1.2 TLSv1.3;
    ssl_session_tickets off;
    ssl_certificate {quote(certificate)};
    ssl_certificate_key {quote(key)};
    server {{
        listen 0.0.0.0:{https} ssl;
        listen [::]:{https} ssl ipv6only=on;
        server_name {origin.hostname};
        # Preserve the real Host; do not manufacture a trusted browser origin.
        if ($http_host != {quote(origin.netloc)}) {{ return 421; }}
        add_header Strict-Transport-Security "max-age=31536000" always;
        client_max_body_size 0;
        client_body_timeout 300s;
        location / {{
            proxy_pass http://127.0.0.1:{backend['port']};
            proxy_http_version 1.1;
            proxy_set_header Host $http_host;
            proxy_set_header Connection "";
            proxy_set_header Forwarded "";
            proxy_set_header X-Forwarded-For "";
            proxy_set_header X-Forwarded-Host "";
            proxy_set_header X-Forwarded-Proto "";
            proxy_set_header X-Real-IP "";
            proxy_request_buffering off;
            proxy_buffering off;
            proxy_read_timeout 300s;
            proxy_send_timeout 300s;
        }}
    }}
}}
'''
    stream_config = f'''stream {{
    server {{
        listen 0.0.0.0:{tcp} ssl;
        listen [::]:{tcp} ssl ipv6only=on;
        ssl_protocols TLSv1.2 TLSv1.3;
        ssl_session_tickets off;
        ssl_certificate {quote(certificate)};
        ssl_certificate_key {quote(key)};
        ssl_handshake_timeout 10s;
        proxy_connect_timeout 5s;
        proxy_timeout 120s;
        proxy_pass 127.0.0.1:{backend['notification_port']};
    }}
}}
'''
    return common + ('' if tcp_only else http_config) + stream_config


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--defer-certificate-check', action='store_true', help='Render before certificate issuance; nginx -t must validate certificate/key before launch')
    parser.add_argument('--tcp-only', action='store_true', help='Only proxy TLS notifications; an existing Caddy handles HTTPS')
    parser.add_argument('--config', required=True, type=Path)
    parser.add_argument('--server', type=Path, default=Path('build/spark_server'))
    parser.add_argument('--certificate', required=True, type=Path)
    parser.add_argument('--key', required=True, type=Path)
    parser.add_argument('--stream-module', type=Path, default=Path('/usr/lib/nginx/modules/ngx_stream_module.so'))
    parser.add_argument('--runtime', required=True, type=Path)
    parser.add_argument('--output', required=True, type=Path)
    args = parser.parse_args()
    result = subprocess.run([str(args.server.resolve()), '--config', str(args.config.resolve()),
                             '--remote', '--check-config'], capture_output=True, text=True)
    if result.returncode:
        parser.error(result.stderr.strip())
    try:
        runtime = args.runtime.resolve()
        paths = (args.stream_module,) if args.defer_certificate_check else (args.certificate, args.key, args.stream_module)
        for path in paths:
            if not path.is_file():
                raise ValueError('Certificate, key and stream module must exist')
        output = render(json.loads(result.stdout), args.certificate.resolve(), args.key.resolve(),
                        args.stream_module.resolve(), runtime, args.tcp_only)
        # Fail instead of silently replacing an operator's existing config.
        with args.output.open('x') as file:
            file.write(output)
        runtime.mkdir(mode=0o700, parents=True, exist_ok=True)
    except (ValueError, OSError) as error:
        parser.error(str(error))
    print('Proxy configuration written. Validate with nginx -t, then start SPARK with --remote.')


if __name__ == '__main__':
    main()
